/** Days from today, used so demo deadlines always look live. */
const fromNow = (days: number, hour = 23, minute = 59) => {
  const date = new Date()
  date.setDate(date.getDate() + days)
  date.setHours(hour, minute, 0, 0)
  return date.toISOString()
}

